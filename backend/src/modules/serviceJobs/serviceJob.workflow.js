const stageByStatus = new Map(
  SERVICE_JOB_STAGES.flatMap((stage) => stage.statuses.map((status) => [status, stage])),
);

const canUsePermission = (user, permission) => {
  const permissions = user?.permissions || [];
  return permissions.includes('*') || permissions.includes(permission);
};

export const serviceStageForStatus = (status) => stageByStatus.get(status) || SERVICE_JOB_STAGES[SERVICE_JOB_STAGES.length - 1];

export const statusesForServiceStage = (stageKey) =>
  SERVICE_JOB_STAGES.find((stage) => stage.key === stageKey)?.statuses || [];

export const serviceActionsForStatus = (status, user = null) =>
  SERVICE_JOB_ACTIONS.filter((action) => {
    if (!action.allowed_statuses.includes(status)) return false;
    return !user || canUsePermission(user, action.permission);
  });

export const serviceWorkflowMetadata = () => ({
  stages: SERVICE_JOB_STAGES,
  statuses: SERVICE_JOB_STATUSES.map((status) => ({
    status,
    stage: serviceStageForStatus(status).key,
    ...SERVICE_JOB_STATUS_META[status],
  })),
  sections: SERVICE_JOB_SECTIONS,
  status_meta: SERVICE_JOB_STATUS_META,
  actions: SERVICE_JOB_ACTIONS,
  inactive_statuses: INACTIVE_SERVICE_JOB_STATUSES,
});
