export const translateUiText = (text, language = "ar") => {
  if (language !== "ar") return text;

  const value = String(text ?? "");
  const trimmed = value.trim();
  if (!trimmed) return value;

  const exact = arText[trimmed];
  if (exact) return value.replace(trimmed, exact);

  for (const [pattern, handler] of arPatterns) {
    const match = trimmed.match(pattern);
    if (match) return value.replace(trimmed, handler(...match));
  }

  const colonMatch = trimmed.match(/^([^:]+):\s*(.+)$/);
  if (colonMatch && arText[colonMatch[1]]) {
    return value.replace(trimmed, `${arText[colonMatch[1]]}: ${colonMatch[2]}`);
  }

  return value;
};
